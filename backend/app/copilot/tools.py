def window(period: str, today: date) -> tuple[date, date, str]:
    if period == "today":
        return today, today + timedelta(days=1), "today"
    if period == "yesterday":
        return today - timedelta(days=1), today, "yesterday"
    if period in ("this_week", "last_week"):
        s = today - timedelta(days=today.weekday())
        if period == "last_week":
            return s - timedelta(days=7), s, "last week"
        return s, s + timedelta(days=7), "this week"
    if period == "this_year":
        return today.replace(month=1, day=1), today.replace(year=today.year + 1, month=1, day=1), f"so far in {today.year}"
    s = today.replace(day=1)
    if period == "last_month":
        p = (s - timedelta(days=1)).replace(day=1)
        return p, s, p.strftime("in %B")
    e = s.replace(year=s.year + 1, month=1) if s.month == 12 else s.replace(month=s.month + 1)
    return s, e, s.strftime("in %B")


def money(v, cur: str) -> str:
    sym = {"GBP": "£", "EUR": "€", "USD": "$"}.get(cur, cur + " ")
    return f"{'-' if Decimal(v) < 0 else ''}{sym}{abs(Decimal(v)):,.2f}"


class Ctx:
    def __init__(self, db: Session, user_id: UUID, hid: UUID, hname: str, home: str):
        self.db, self.user_id, self.hid, self.hname, self.home = db, user_id, hid, hname, home
        self.rates = rate_table(db, hid)
        self.today = date.today()


def _included(alias: str = "t") -> str:
    return f"""{alias}.account_id IN (SELECT ha.account_id FROM household_accounts ha
                 JOIN accounts a2 ON a2.id = ha.account_id
                 JOIN memberships ow ON ow.household_id = ha.household_id AND ow.user_id = a2.owner_user_id
                WHERE ha.household_id = :h AND ha.attribution = 'include')"""


def spending(c: Ctx, it: Intent) -> dict:
    s, e, label = window(it.period, c.today)
    where, params = ["t.amount < 0", "t.transfer_group IS NULL", "t.posted_on >= :s", "t.posted_on < :e", _included()], \
        {"h": c.hid, "s": s, "e": e}
    what = "in total"
    if it.category:
        where.append("t.category = :cat")
        params["cat"], what = it.category, f"on {it.category}"
    elif it.merchant:
        where.append("(t.merchant ILIKE :m OR t.merchant_key ILIKE :m OR t.description ILIKE :m)")
        params["m"], what = f"%{it.merchant}%", f"at {it.merchant.title()}"
    if it.member:
        where.append("u.display_name ILIKE :mem")
        params["mem"] = f"%{it.member}%"
    rows = c.db.execute(text(f"""
        SELECT t.id, t.posted_on, coalesce(t.merchant, t.description) AS name, t.amount, t.currency, a.name AS account
          FROM transactions t JOIN accounts a ON a.id = t.account_id JOIN users u ON u.id = a.owner_user_id
         WHERE {' AND '.join(where)} ORDER BY t.amount ASC"""), params).all()
    total, missing = Decimal(0), set()
    for r in rows:
        v = convert(-Decimal(r.amount), r.currency, c.home, c.rates)
        if v is None:
            missing.add(r.currency)
        else:
            total += v
    who = f"{it.member.title()} " if it.member else ("You all " if True else "")
    answer = f"{c.hname} spent {money(total, c.home)} {what} {label}" + (f" ({len(rows)} payment{'s' if len(rows) != 1 else ''})." if rows else ".")
    if it.member:
        answer = f"{it.member.title()} spent {money(total, c.home)} {what} {label}."
    if missing:
        answer += f" Not counted: spending in {', '.join(sorted(missing))} (no exchange rate)."
    cites = [{"label": f"{r.posted_on:%-d %b} {r.name}, {money(r.amount, r.currency)}, {r.account}"} for r in rows[:5]]
    return {"answer": answer, "citations": cites, "link": "#/activity" + (f"?q={it.merchant}" if it.merchant else "")}


def balance(c: Ctx, it: Intent) -> dict:
    from app.routers.accounts import _ACCOUNT_SELECT
    rows = c.db.execute(text(_ACCOUNT_SELECT + " WHERE a.id IN (SELECT app_visible_account_ids()) ORDER BY a.name"),
                        {"u": c.user_id}).all()
    if it.account:
        rows = [r for r in rows if it.account.lower() in r.name.lower()] or rows
    known = [r for r in rows if r.balance is not None]
    if not known:
        return {"answer": "I don't have a balance yet: import a statement that includes a balance column.", "citations": []}
    lines = [f"{r.name}: {money(r.balance, r.currency)}" for r in known]
    return {"answer": "Latest balances: " + "; ".join(lines) + ".",
            "citations": [{"label": f"{r.name}: from the last imported statement" if r.type != "cash" else f"{r.name}: cash wallet entries"} for r in known],
            "link": "#/accounts"}


def _stock(c: Ctx):
    from app.routers.inventory import household_stock
    return household_stock(c.db, c.hid)


def low_stock(c: Ctx, it: Intent) -> dict:
    low = [p for p in _stock(c) if p.low]
    if not low:
        return {"answer": "Nothing's running low (based on the restock levels you've set).", "citations": [], "link": "#/pantry"}
    return {"answer": "Running low: " + ", ".join(f"{p.name} (have {p.on_hand:g})" for p in low) + ".",
            "citations": [{"label": f"{p.name}: restock at {p.restock_below:g}"} for p in low], "link": "#/pantry"}


def expiring(c: Ctx, it: Intent) -> dict:
    out = [(p.name, l) for p in _stock(c) for l in p.lots if l.state in ("soon", "expired")]
    if not out:
        return {"answer": "Nothing in the pantry is close to its use-by date.", "citations": [], "link": "#/pantry"}
    def say(n, l):
        return f"{n} ({'expired' if l.state == 'expired' else 'today' if l.days_left == 0 else f'{l.days_left} day' + ('s' if l.days_left != 1 else '')})"
    return {"answer": "Use soon: " + ", ".join(say(n, l) for n, l in out) + ".",
            "citations": [{"label": f"{n}: use by {l.expires_on:%-d %b}"} for n, l in out], "link": "#/pantry"}


def stock_lookup(c: Ctx, it: Intent) -> dict:
    name = (it.product or "").lower()
    hits = [p for p in _stock(c) if name and name in p.name.lower()]
    if not hits:
        return {"answer": f"I can't see any {it.product} in the pantry.", "citations": [], "link": "#/pantry"}
    return {"answer": "; ".join(f"{p.name}: {p.amount_label or f'{p.on_hand:g}'} in stock" for p in hits) + ".",
            "citations": [], "link": "#/pantry"}


def bills(c: Ctx, it: Intent) -> dict:
    from app.routers.recurring import household_recurring
    from app.routers.subscriptions import household_subscriptions
    soon = c.today + timedelta(days=14)
    rec = [r for r in household_recurring(c.db, c.hid) if r.direction == "out" and r.status == "active" and r.next_date <= soon]
    subs = [s for s in household_subscriptions(c.db, c.hid) if s.status != "cancelled" and s.next_renewal and s.next_renewal <= soon
            and s.auto_renew and not s.linked]
    if not rec and not subs:
        return {"answer": "No bills or renewals due in the next two weeks.", "citations": [], "link": "#/bills"}
    items = [(r.next_date, r.name, abs(r.expected_amount), r.currency) for r in rec] + \
            [(s.next_renewal, s.provider, s.amount, s.currency) for s in subs]
    items.sort()
    return {"answer": "Due in the next two weeks: " + "; ".join(f"{n} {money(a, cur)} on {d:%-d %b}" for d, n, a, cur in items) + ".",
            "citations": [{"label": f"{n}: from your regular payments" } for d, n, a, cur in items[:5]], "link": "#/bills"}


def budgets(c: Ctx, it: Intent) -> dict:
    from app.routers.budgets import visible_budgets
    bs = visible_budgets(c.db, c.hid, c.user_id)
    if not bs:
        return {"answer": "There are no budgets yet. Try “set a £200 budget for groceries”.", "citations": [], "link": "#/budgets"}
    return {"answer": "; ".join(f"{b.label}: {money(b.spent, b.currency)} of {money(b.amount, b.currency)} ({b.message})" for b in bs[:6]) + ".",
            "citations": [], "link": "#/budgets"}


def goals(c: Ctx, it: Intent) -> dict:
    from app.routers.goals import household_goals
    gs = household_goals(c.db, c.hid, c.user_id)
    if it.goal:
        gs = [g for g in gs if it.goal.lower() in g.name.lower()] or gs
    if not gs:
        return {"answer": "There are no savings goals yet.", "citations": [], "link": "#/goals"}
    return {"answer": "; ".join(f"{g.name}: {money(g.saved, g.currency)} of {money(g.target, g.currency)} ({int(g.progress * 100)}%)" for g in gs) + ".",
            "citations": [{"label": f"{m.name} put in {money(m.saved, g.currency)} toward {g.name}"} for g in gs[:2] for m in g.members[:3]],
            "link": "#/goals"}


def by_member(c: Ctx, it: Intent) -> dict:
    s, e, label = window(it.period, c.today)
    rows = c.db.execute(text(f"""SELECT u.display_name AS name, t.currency, sum(-t.amount) AS v, count(*) AS n
                                  FROM transactions t JOIN accounts a ON a.id = t.account_id JOIN users u ON u.id = a.owner_user_id
                                 WHERE t.amount < 0 AND t.transfer_group IS NULL AND t.posted_on >= :s AND t.posted_on < :e AND {_included()}
                                 GROUP BY 1, 2"""), {"h": c.hid, "s": s, "e": e}).all()
    tot: dict = {}
    for r in rows:
        v = convert(Decimal(r.v), r.currency, c.home, c.rates)
        if v is not None:
            tot[r.name] = tot.get(r.name, Decimal(0)) + v
    if not tot:
        return {"answer": f"No shared spending {label}.", "citations": []}
    ranked = sorted(tot.items(), key=lambda kv: -kv[1])
    return {"answer": f"Spending {label} by whose account it came from: " + "; ".join(f"{n} {money(v, c.home)}" for n, v in ranked) + ".",
            "citations": [{"label": "Accounts shared into the household totals"}], "link": "#/insights"}


def top_shops(c: Ctx, it: Intent) -> dict:
    s, e, label = window(it.period, c.today)
    rows = c.db.execute(text(f"""SELECT coalesce(t.merchant, initcap(t.merchant_key), t.description) AS name, t.currency,
                                        sum(-t.amount) AS v, count(*) AS n FROM transactions t
                                 WHERE t.amount < 0 AND t.transfer_group IS NULL AND t.posted_on >= :s AND t.posted_on < :e AND {_included()}
                                 GROUP BY 1, 2"""), {"h": c.hid, "s": s, "e": e}).all()
    tot: dict = {}
    for r in rows:
        v = convert(Decimal(r.v), r.currency, c.home, c.rates)
        if v is not None:
            tot[r.name] = tot.get(r.name, Decimal(0)) + v
    if not tot:
        return {"answer": f"No spending {label} yet.", "citations": []}
    ranked = sorted(tot.items(), key=lambda kv: -kv[1])[:5]
    return {"answer": f"Top places {label}: " + "; ".join(f"{n} {money(v, c.home)}" for n, v in ranked) + ".",
            "citations": [], "link": "#/insights"}


# ---------------- action proposals (executed only after the user confirms) ----------------

def propose(c: Ctx, it: Intent) -> dict:
    """Validate an action against what exists, and describe it for the confirmation card."""
    if it.tool == "set_budget":
        if not it.category or not it.amount:
            return {"answer": "Which category and how much? For example: “set a £200 monthly budget for groceries”."}
        per = {"daily": "daily", "weekly": "weekly", "monthly": "monthly"}[it.budget_period]
        return {"action": {"kind": "set_budget", "params": {"category": it.category, "amount": round(it.amount, 2), "period": per,
                                                             "currency": c.home},
                           "summary": f"Set a {per} {it.category} budget of {money(it.amount, c.home)} for {c.hname}?"}}
    if it.tool in ("pantry_add", "pantry_use"):
        name = (it.product or "").strip()
        if not name:
            return {"answer": "Which item?"}
        hits = [p for p in _stock(c) if name.lower() in p.name.lower() or p.name.lower() in name.lower()]
        qty = it.quantity or 1
        if it.tool == "pantry_use":
            if not hits:
                return {"answer": f"I can't find {name} in the pantry."}
            p = hits[0]
            return {"action": {"kind": "pantry_use", "params": {"product_id": str(p.id), "quantity": qty},
                               "summary": f"Mark {qty:g}× {p.name} as used (you have {p.on_hand:g})?"}}
        if hits:
            p = hits[0]
            return {"action": {"kind": "pantry_add", "params": {"product_id": str(p.id), "quantity": qty},
                               "summary": f"Add {qty:g}× {p.name} to the pantry?"}}
        return {"action": {"kind": "pantry_add", "params": {"name": name.capitalize()[:120], "quantity": qty},
                           "summary": f"Add {qty:g}× {name} to the pantry as a new item?"}}
    if it.tool == "goal_contribute":
        from app.routers.goals import household_goals
        gs = household_goals(c.db, c.hid, c.user_id)
        hits = [g for g in gs if it.goal and (it.goal.lower() in g.name.lower() or g.name.lower() in it.goal.lower())]
        if not hits or not it.amount:
            names = ", ".join(g.name for g in gs) or "none yet"
            return {"answer": f"Which goal and how much? Your goals: {names}."}
        g = hits[0]
        return {"action": {"kind": "goal_contribute", "params": {"goal_id": str(g.id), "amount": round(it.amount, 2)},
                           "summary": f"Record {money(it.amount, g.currency)} from you toward {g.name}?"}}
    return {"answer": "I can't do that yet."}


